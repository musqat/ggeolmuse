-- user-service 가 입금한 배당. 같은 계좌 · 종목 · 배당락일은 한 번만 반영
-- (Kafka 가 같은 지급을 다시 보내거나 market-data 가 배당을 다시 모아도)
CREATE TABLE IF NOT EXISTS dividend_settlements (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id   BIGINT NOT NULL,
    symbol       VARCHAR(20) NOT NULL,
    ex_date      DATE NOT NULL,
    amount       DECIMAL(15,4) NOT NULL,
    processed_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_dividend_settlements UNIQUE (account_id, symbol, ex_date),
    CONSTRAINT fk_dividend_settlements_account FOREIGN KEY (account_id) REFERENCES account(id) ON DELETE CASCADE
);
